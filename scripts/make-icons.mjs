// Writes web/shared/icons.js from the Lucide icon set (ISC licence), keeping only the icons the pages use.
//   npm install lucide-static   (anywhere)   then   node scripts/make-icons.mjs <path to lucide-static/icons>
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const from = process.argv[2];
const names = ['globe', 'moon', 'party-popper', 'message-circle', 'coffee', 'pencil', 'palette', 'gamepad-2', 'messages-square', 'handshake', 'swords', 'shuffle', 'ear', 'megaphone', 'scale',
  'music', 'clapperboard', 'utensils', 'plane', 'book-open', 'sparkles', 'volleyball', 'laptop', 'leaf', 'paw-print', 'thumbs-up', 'thumbs-down', 'check', 'x', 'calendar-plus', 'link', 'hand',
  'map-pin', 'arrow-left', 'arrow-right', 'trash-2', 'undo-2', 'eraser', 'refresh-cw', 'log-out', 'flag', 'lock', 'lock-open', 'search', 'users', 'heart', 'languages'];
const out = {};
for (const name of names) {
  const svg = readFileSync(join(from, name + '.svg'), 'utf8');
  out[name] = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[^>]*>/, '').replace('</svg>', '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
}
const file = join(dirname(fileURLToPath(import.meta.url)), '../web/shared/icons.js');
writeFileSync(file, `/* Line icons from Lucide (https://lucide.dev), ISC licence. Generated by scripts/make-icons.mjs: do not edit by hand.\n   One colour only: they take the colour of the text around them, white on dark and black on light. */\nD.icons = ${JSON.stringify(out, null, 1)};\n`);
console.log(names.length, 'icons,', readFileSync(file).length, 'bytes');
